# Topic: Operators
a = 10
b = 3

print("======= OPERATORS =======")
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor division:", a // b)
print("Modulus:", a % b)
print("Power:", a ** b)

print("\n======= COMPARISON OPERATORS =======")
print("a == b:", a == b)
print("a > b:", a > b)
print("a < b:", a < b)
print("a != b:", a != b)
